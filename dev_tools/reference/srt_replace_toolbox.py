def create_translation_excel(txt_files, excel_file, log_callback, ignore_return_option):
    
    def parse_block(block_text):
        lines = [line.strip() for line in block_text.strip().split('\n') if line.strip()]
        if not lines: return None, None, None, None
        header_lines, jp_lines, ch_lines = [], [], []
        line_idx = 0
        while line_idx < len(lines) and (lines[line_idx].startswith('#') or lines[line_idx].startswith('; >')):
            header_lines.append(lines[line_idx]); line_idx += 1
        if not header_lines: return None, None, None, None
        while line_idx < len(lines) and lines[line_idx].startswith(';'):
            jp_lines.append(lines[line_idx].lstrip(';').strip()); line_idx += 1
        while line_idx < len(lines) and not lines[line_idx].startswith((';', '#')):
            ch_lines.append(lines[line_idx]); line_idx += 1
        if not (header_lines and jp_lines and ch_lines): return None, None, None, None
        header_text = " ".join(header_lines); category = ""
        if "Choice" in header_text and "handler:Trial" in header_text: category = "#反驳"
        elif "Choice" in header_text: category = "#选项"
        elif "print" in header_text and "Debate" in header_text:
            category = "#庭审正"
            roll_match = std_re.search(r'roll:([-\d.]+)', header_text)
            if roll_match:
                try:
                    roll_value = float(roll_match.group(1))
                    if roll_value > 0: category = "#庭审左"
                    elif roll_value < 0: category = "#庭审右"
                except ValueError: pass
        elif "print" in header_text: category = "#庭审"
        if not category: category = "#台词"
        return jp_lines, ch_lines, category, header_text

    all_japanese_texts, all_chinese_texts, all_categories = [], [], []
    
    for file_index, txt_file in enumerate(txt_files):
        log_callback(f"开始读取文件: {os.path.basename(txt_file)}...")
        with open(txt_file, 'r', encoding='utf-8') as f:
            content = f.read()
        
        log_callback(f"文件读取完毕，开始分割...")
        content += '\n#'
        blocks = std_re.split(r'(?=^#)', content, flags=std_re.MULTILINE)
        log_callback(f"分割完成，得到 {len(blocks) -1} 个文本块。开始整理格式...")
        
        if len(blocks) <= 1:
            log_callback(f"警告: 文件 {os.path.basename(txt_file)} 中没有找到以'#'开头的台词块。")
            continue

        japanese_texts, chinese_texts, categories = [], [], []
        
        block_idx = 1
        while block_idx < len(blocks):
            jp_lines, ch_lines, category, header = parse_block(blocks[block_idx])
            if not category:
                block_idx += 1
                continue

            # 【不合并模式修改】
            # 采用统一逻辑处理所有文本块，不再区分 #选项/#反驳 和其他类型。
            # 这将确保每个选项在Excel中都独占一行。
            
            # 1. 清理日文和中文行，并用单个 <br> 连接
            jp_cleaned = "<br>".join(filter(None, jp_lines))
            ch_cleaned = "<br>".join(filter(None, ch_lines))

            # 2. 统一进行“忽略返回”检查
            if ignore_return_option and ch_cleaned == '返回':
                log_callback(f"  -> (已启用) 检测到并忽略了中文为 '返回' 的条目。")
                block_idx += 1
                continue

            # 3. 如果日文和中文都不为空，则添加到最终列表
            if jp_cleaned and ch_cleaned:
                japanese_texts.append(jp_cleaned)
                chinese_texts.append(ch_cleaned)
                categories.append(category)
            
            # 4. 移动到下一个块
            block_idx += 1
       
        all_japanese_texts.extend(japanese_texts)
        all_chinese_texts.extend(chinese_texts)
        all_categories.extend(categories)
        log_callback(f"文件 {os.path.basename(txt_file)} 处理完毕，找到 {len(japanese_texts)} 条有效条目。")

        if file_index < len(txt_files) - 1:
            all_japanese_texts.append(None)
            all_chinese_texts.append(None)
            all_categories.append(None)
            log_callback(f"--- 在文件 {os.path.basename(txt_file)} 之后插入了一个空白行分隔符 ---")

    log_callback(f"\n所有文件格式整理完毕，共找到 {len([t for t in all_japanese_texts if t is not None])} 条有效条目。正在生成DataFrame...")
    df = pd.DataFrame({'日文': all_japanese_texts, '中文': all_chinese_texts, '分类': all_categories})
   
    log_callback(f"DataFrame生成完毕，共包含 {len(df)} 行。正在保存到Excel文件...")
    df.to_excel(excel_file, index=False)
    return f"成功从 {len(txt_files)} 个文件中提取了 {len([t for t in all_japanese_texts if t is not None])} 条中日文对，已保存！"

def fuzzy_match_and_translate_srt(
    excel_path, srt_in_path, srt_out_path, 
    base_threshold, rebuke_threshold, 
    short_sentence_length, short_sentence_penalty, 
    use_context_rescue, use_legacy_rescue, 
    rescue_candidate_threshold, review_threshold, upgrade_bonus_threshold,
    context_priority_threshold, 
    use_long_text_filter, long_text_threshold, long_text_exemption_threshold,
    use_pool_filter, pool_threshold_minutes, pool_first_match_threshold, 
    use_context_marker, context_marker, use_legacy_marker, legacy_marker,
    skip_first_line_enabled, 
    use_skip_line_competition,
    aggressive_short_sentence_rescue,
    use_advanced_rebuke_rescue, rebuke_anchor_threshold, rebuke_neighborhood_size, rebuke_rescue_threshold,
    use_single_anchor_rescue, single_anchor_threshold, single_anchor_neighborhood,
    single_anchor_aggressive_mode, single_anchor_time_threshold,
    pool_status_callback, progress_callback, should_log_details
):
    logs = []
    def log_message(message):
        if should_log_details:
            logs.append(message)

    if re is None:
        error_msg = "错误：需要安装 'regex' 模块以支持高级标点匹配。\n请在命令行运行: pip install regex"
        logs.append(error_msg)
        raise ImportError(error_msg)
        
    def clean_text_for_matching(text, for_comparison=True):
        if not isinstance(text, str): return ""
        if for_comparison: text = text.replace('<br>', ' ').replace('\n', ' ')
        text = text.replace('\u200b', '').replace('\ufeff', '')
        full_width_chars = "，。？！…．（）「」『』"; half_width_chars = ",.?!..()「」『』"
        translation_table = str.maketrans(full_width_chars, half_width_chars)
        text = text.translate(translation_table)
        text = re.sub(r'\p{P}', '', text); text = re.sub(r'<.*?>', '', text)
        return "".join(text.split())

    REBUKE_TRIGGER_KEYWORDS = {"反論", "反", "謚", "賛成", "偽証", "戻る", "賛", "成", "偽","戻","論"}
    
    master_pool = []
    exemption_pool = [] 
    try:
        df = pd.read_excel(excel_path)
        if '日文' not in df.columns or '中文' not in df.columns or '分类' not in df.columns:
            raise ValueError("Excel文件中必须包含 '日文', '中文', 和 '分类' 三列。")
        df.fillna('', inplace=True)
        
        for index, row in df.iterrows():
            jp_raw = str(row['日文'])
            jp_clean = clean_text_for_matching(jp_raw, for_comparison=True)
            if jp_clean:
                category = str(row['分类']).strip()
                item_data = {
                    'excel_row': index + 2,
                    'jp_raw': jp_raw,
                    'jp_clean': jp_clean,
                    'ch': str(row['中文']),
                    'cat': str(row['分类']),
                    'first_match_time': None
                }
                master_pool.append(item_data)
                if category == '#证物' or category == '':
                    exemption_pool.append(item_data)
        
        rebuke_pool = [item for item in master_pool if item['cat'] == '#反驳']
        rebuke_choices_raw = [item['jp_raw'] for item in rebuke_pool]
        rebuke_choices_cleaned = [clean_text_for_matching(jp, for_comparison=False) for jp in rebuke_choices_raw]
        exemption_choices_clean = [item['jp_clean'] for item in exemption_pool]

        option_pool = [item for item in master_pool if item['cat'] == '#选项']
        option_choices_cleaned = [item['jp_clean'] for item in option_pool]

        log_message(f"成功加载并创建了包含 {len(master_pool)} 条目的主匹配池。")
        log_message(f"创建了包含 {len(exemption_pool)} 条目的豁免池 (证物/空分类)。")
        log_message(f"其中，#反驳 池包含 {len(rebuke_pool)} 条目。")
        log_message(f"其中，#选项 池包含 {len(option_pool)} 条目。")

    except Exception as e: raise IOError(f"读取Excel文件并构建匹配池时出错: {e}")
    
    try:
        subs = pysrt.open(srt_in_path, encoding='utf-8')
        total_subs = len(subs)
        log_message(f"开始处理 {total_subs} 个字幕块...")
    except Exception as e: raise IOError(f"读取SRT文件 '{os.path.basename(srt_in_path)}' 时出错: {e}")
    
    total_pool_size = len(master_pool)
    if use_pool_filter:
        log_message(f"\n动态匹配池已开启 (剔除阈值: {pool_threshold_minutes} 分钟, 计时阈值: {pool_first_match_threshold:.2f})。")
        pool_status_callback(total_pool_size, len(master_pool))

    match_results = []
    for i, sub in enumerate(subs):
        progress_callback(i + 1, total_subs)

        if use_pool_filter:
            indices_to_prune = []
            current_time = sub.start
            threshold_seconds = pool_threshold_minutes * 60
            
            for pool_idx, item in enumerate(master_pool):
                if item['first_match_time'] is not None:
                    time_diff = current_time - item['first_match_time']
                    time_diff_seconds = (time_diff.hours * 3600) + (time_diff.minutes * 60) + time_diff.seconds + (time_diff.milliseconds / 1000.0)
                    if time_diff_seconds > threshold_seconds:
                        indices_to_prune.append(pool_idx)
            
            if indices_to_prune:
                log_message(f"--- [动态池日志] ---")
                log_message(f"时间点: {str(current_time)[:-4]} (字幕块 {sub.index})")
                log_message(f"检测到 {len(indices_to_prune)} 个过期条目，将被永久移除:")
                for pool_idx in sorted(indices_to_prune, reverse=True):
                    item = master_pool.pop(pool_idx)
                    log_message(f"  - Excel行 {item['excel_row']}: '{item['jp_clean'][:30]}...'")
                log_message(f"--- [日志结束] ---")
                pool_status_callback(total_pool_size, len(master_pool))

        original_jp_text = sub.text.lstrip('\ufeff')
        is_match, final_text, best_score, excel_index = False, "", 0.0, -1
        match_method = 'none'
        low_score_candidate = None 
        
        cleaned_for_match = clean_text_for_matching(original_jp_text, for_comparison=True)

        if not is_match and exemption_pool and cleaned_for_match:
            priority_threshold = max(base_threshold, long_text_exemption_threshold) 
            exempted_match = process.extractOne(
                cleaned_for_match, exemption_choices_clean, 
                scorer=fuzz.ratio, score_cutoff=priority_threshold * 100
            )
            if exempted_match:
                _, score, matched_pool_index = exempted_match
                matched_item = exemption_pool[matched_pool_index]
                is_match, best_score = True, score / 100.0
                match_method = 'priority_exempted'
                final_text = str(matched_item['ch']).replace('<br>', '\\N') + str(matched_item['cat'])
                excel_index = matched_item['excel_row'] - 2
                log_message(f"块 {sub.index}: [优先豁免] 匹配到证物/豁免池 (相似度: {best_score:.2f}, Excel行: {matched_item['excel_row']})。")

        if not is_match and use_long_text_filter:
            if cleaned_for_match and len(cleaned_for_match) >= long_text_threshold:
                log_message(f"块 {sub.index}: [长句过滤器] 触发 (文本长度 {len(cleaned_for_match)} >= {long_text_threshold})。")
                log_message(f"  -> [豁免检查] 之前的优先检查未命中。跳过此长句。")
                match_method = 'long_text_filtered'
                match_results.append({'sub': sub, 'original_text': original_jp_text, 'translated_text': '', 'is_match': False, 'score': 0.0, 'excel_index': -1, 'match_method': match_method, 'low_score_candidate': None})
                continue

        cleaned_original_for_keyword_check = original_jp_text.replace('\n', ' ')
        is_rebuke_case = any(keyword in cleaned_original_for_keyword_check for keyword in REBUKE_TRIGGER_KEYWORDS)
        
        line_count = original_jp_text.count('\n') + 1
        char_count = len(cleaned_for_match)
        is_potential_option_case = (1 < line_count <= 3 and char_count < 4)

        def run_rebuke_mode(is_retroactive=False):
            log_prefix = "[反驳模式追认]" if is_retroactive else "[反驳模式]"
            log_message(f"块 {sub.index}: {log_prefix} 触发。")
            
            if use_advanced_rebuke_rescue:
                log_message(f"  -> [高级救援] 已启用，开始执行...")
                rebuke_is_match, rebuke_final_text, rebuke_best_score = _handle_advanced_rebuke_mode(
                    original_jp_text, rebuke_pool, rebuke_anchor_threshold, 
                    rebuke_neighborhood_size, rebuke_rescue_threshold, REBUKE_TRIGGER_KEYWORDS, 
                    clean_text_for_matching, context_marker if use_context_marker else "", log_message
                )
                if rebuke_is_match:
                    log_message(f"  -> [高级救援] 成功，采纳结果。")
                    return True, rebuke_final_text, rebuke_best_score, -1, 'direct_rebuke'
                else:
                    log_message(f"  -> [高级救援] 失败，无有效结果。")
                    return False, "", 0.0, -1, 'rebuke_failed'
            else:
                log_message(f"  -> [常规模式] 执行...")
                lines = original_jp_text.split('\n')
                successful_translations = []
                for line in lines:
                    cleaned_line_for_match = clean_text_for_matching(line, for_comparison=False)
                    if not cleaned_line_for_match or line.strip() in REBUKE_TRIGGER_KEYWORDS: continue
                    best_overall_match = process.extractOne(cleaned_line_for_match, rebuke_choices_cleaned, scorer=fuzz.ratio) if rebuke_choices_cleaned else None
                    if best_overall_match:
                        _, score, idx = best_overall_match
                        if score >= rebuke_threshold * 100:
                            matched_raw_jp = rebuke_choices_raw[idx]
                            ch = next((item['ch'] for item in rebuke_pool if item['jp_raw'] == matched_raw_jp), "")
                            successful_translations.append(ch.replace('<br>', '\\N'))
                            log_message(f"    - 选项 '{line.strip()[:20]}...' 匹配成功 (分数: {score:.2f})。")
                        else:
                            log_message(f"    - 选项 '{line.strip()[:20]}...' 匹配失败 (最高分: {score:.2f})。")
                    else:
                        log_message(f"    - 选项 '{line.strip()[:20]}...' 匹配失败 (无可用对照)。")
                if successful_translations:
                    log_message(f"  -> [常规模式] 采纳结果。")
                    return True, "\\N\\N".join(successful_translations) + "#反驳", 1.0, -1, 'direct_rebuke'
                else:
                    log_message(f"  -> [常规模式] 失败。")
                    return False, "", 0.0, -1, 'rebuke_failed'

        def run_option_mode(is_retroactive=False):
            log_prefix = "[选项模式追认]" if is_retroactive else "[选项模式]"
            log_message(f"块 {sub.index}: {log_prefix} 触发。")

            if not option_pool:
                log_message(f"  -> 失败，#选项 匹配池为空。")
                return False, "", 0.0, -1, 'option_failed_no_pool'

            if not cleaned_for_match:
                log_message(f"  -> 失败，SRT文本清理后为空。")
                return False, "", 0.0, -1, 'option_failed_empty_text'

            best_match = process.extractOne(
                cleaned_for_match,
                option_choices_cleaned,
                scorer=fuzz.ratio,
                score_cutoff=base_threshold * 100
            )

            if best_match:
                _, score, idx = best_match
                matched_item = option_pool[idx]
                anchor_excel_row = matched_item['excel_row']
                log_message(f"  -> 锚点匹配成功: Excel行 {anchor_excel_row} (分数: {score/100:.2f}) - '{matched_item['ch']}'")

                master_index = -1
                for i, item in enumerate(master_pool):
                    if item['excel_row'] == anchor_excel_row:
                        master_index = i
                        break
                
                if master_index == -1:
                    log_message(f"  -> 错误：无法在主池中定位锚点。")
                    return False, "", 0.0, -1, 'option_error_index'

                group_start = master_index
                while group_start > 0 and master_pool[group_start - 1]['cat'] == '#选项':
                    group_start -= 1
                
                group_end = master_index
                while group_end < len(master_pool) - 1 and master_pool[group_end + 1]['cat'] == '#选项':
                    group_end += 1
                
                bundled_translations = []
                log_message(f"  -> 正在打包 Excel行 {master_pool[group_start]['excel_row']} 到 {master_pool[group_end]['excel_row']} 的选项组...")

                for i in range(group_start, group_end + 1):
                    item = master_pool[i]
                    trans = str(item['ch']).replace('<br>', '\\N').replace('<br><br>', '\\N\\N')
                    bundled_translations.append(trans)
                
                final_translation = "\\N\\N".join(bundled_translations) + "#选项"
                return True, final_translation, score / 100.0, matched_item['excel_row'] - 2, 'direct_option_bundled'
            else:
                log_message(f"  -> 失败，在 #选项 池中未找到足够相似的条目。")
                return False, "", 0.0, -1, 'option_failed_no_match'

        if not is_match and is_rebuke_case:
            is_match, final_text, best_score, excel_index, match_method = run_rebuke_mode()
        
        if not is_match and is_potential_option_case:
            log_message(f"块 {sub.index}: [启发式触发] 检测到潜在选项格式 (行数: {line_count}, 字数: {char_count})，尝试进入选项模式...")
            is_match, final_text, best_score, excel_index, match_method = run_option_mode()
        
        if not is_match and master_pool:
            matched_item = None
            lines = original_jp_text.split('\n')
            current_choices = [item['jp_clean'] for item in master_pool]
            
            if use_skip_line_competition:
                full_match_candidate, skip_match_candidate = None, None
                cleaned_srt_full = clean_text_for_matching(original_jp_text)
                if cleaned_srt_full:
                    dynamic_threshold_full = min(base_threshold + short_sentence_penalty, 1.0) if len(cleaned_srt_full) <= short_sentence_length else base_threshold
                    full_match_candidate = process.extractOne(cleaned_srt_full, current_choices, scorer=fuzz.ratio, score_cutoff=dynamic_threshold_full * 100)
                if skip_first_line_enabled and len(lines) > 1 and len(lines[0].strip()) <= 5:
                    text_without_first_line = '\n'.join(lines[1:])
                    cleaned_srt_pass1 = clean_text_for_matching(text_without_first_line)
                    if cleaned_srt_pass1:
                        dynamic_threshold_skip = min(base_threshold + short_sentence_penalty, 1.0) if len(cleaned_srt_pass1) <= short_sentence_length else base_threshold
                        skip_match_candidate = process.extractOne(cleaned_srt_pass1, current_choices, scorer=fuzz.ratio, score_cutoff=dynamic_threshold_skip * 100)
                
                score_full = full_match_candidate[1] if full_match_candidate else -1
                score_skip = skip_match_candidate[1] if skip_match_candidate else -1
                final_winner, match_type = (None, "未知")
                
                if score_skip > score_full:
                    log_message(f"块 {sub.index}: [首行竞争-胜出] 移除干扰项 '{lines[0].strip()}' 后分数提升 ({score_full:.1f} -> {score_skip:.1f})。")
                    final_winner, match_type = skip_match_candidate, "跳过首行匹配"
                elif score_full >= 0:
                    final_winner, match_type = full_match_candidate, "全句匹配"
                
                if final_winner:
                    _, score, matched_pool_index = final_winner
                    matched_item = master_pool[matched_pool_index]
                    temp_best_score = score / 100.0
                    temp_final_text = str(matched_item['ch']).replace('<br>', '\\N').replace('<br><br>', '\\N\\N') + str(matched_item['cat'])
                    temp_excel_index = matched_item['excel_row'] - 2
                    
                    # 【修复点1】如果命中 #选项 或 #反驳，即使分低，也不进待定区，强制视为 is_match，以便触发追认
                    if use_context_rescue and temp_best_score < context_priority_threshold and matched_item['cat'] not in ['#选项', '#反驳']:
                        log_message(f"块 {sub.index}: [{match_type}] 命中低分匹配 (分数: {temp_best_score:.2f} < {context_priority_threshold:.2f})。")
                        log_message(f"  -> [上下文优先] 结果被暂存，优先尝试上下文救援。")
                        is_match = False
                        best_score = temp_best_score
                        low_score_candidate = {
                            'translated_text': temp_final_text,
                            'score': temp_best_score,
                            'excel_index': temp_excel_index,
                            'match_method': 'direct_low_score'
                        }
                    else:
                        is_match, best_score, match_method = True, temp_best_score, 'direct'
                        final_text = temp_final_text
                        excel_index = temp_excel_index
                        log_message(f"块 {sub.index}: [{match_type}] 成功 (相似度: {best_score:.2f}, Excel行: {matched_item['excel_row']})")

            else: # 非竞争模式
                best_match, match_type = None, "未知"
                if skip_first_line_enabled and len(lines) > 1 and len(lines[0].strip()) <= 5:
                    text_without_first_line = '\n'.join(lines[1:])
                    cleaned_srt_pass1 = clean_text_for_matching(text_without_first_line)
                    if cleaned_srt_pass1:
                        dynamic_threshold = min(base_threshold + short_sentence_penalty, 1.0) if len(cleaned_srt_pass1) <= short_sentence_length else base_threshold
                        pass1_match = process.extractOne(cleaned_srt_pass1, current_choices, scorer=fuzz.ratio, score_cutoff=dynamic_threshold * 100)
                        if pass1_match: best_match, match_type = pass1_match, "跳过首行匹配"
                if not best_match:
                    cleaned_srt_full = clean_text_for_matching(original_jp_text)
                    if cleaned_srt_full:
                        dynamic_threshold = min(base_threshold + short_sentence_penalty, 1.0) if len(cleaned_srt_full) <= short_sentence_length else base_threshold
                        full_match = process.extractOne(cleaned_srt_full, current_choices, scorer=fuzz.ratio, score_cutoff=dynamic_threshold * 100)
                        if full_match: best_match, match_type = full_match, "全句匹配"
                
                if best_match:
                    _, score, matched_pool_index = best_match
                    matched_item = master_pool[matched_pool_index]
                    temp_best_score = score / 100.0
                    temp_final_text = str(matched_item['ch']).replace('<br>', '\\N').replace('<br><br>', '\\N\\N') + str(matched_item['cat'])
                    temp_excel_index = matched_item['excel_row'] - 2

                    # 【修复点2】非竞争模式下，同样逻辑
                    if use_context_rescue and temp_best_score < context_priority_threshold and matched_item['cat'] not in ['#选项', '#反驳']:
                        log_message(f"块 {sub.index}: [{match_type}] 命中低分匹配 (分数: {temp_best_score:.2f} < {context_priority_threshold:.2f})。")
                        log_message(f"  -> [上下文优先] 结果被暂存，优先尝试上下文救援。")
                        is_match = False
                        best_score = temp_best_score
                        low_score_candidate = {
                            'translated_text': temp_final_text,
                            'score': temp_best_score,
                            'excel_index': temp_excel_index,
                            'match_method': 'direct_low_score'
                        }
                    else:
                        is_match, best_score, match_method = True, temp_best_score, 'direct'
                        final_text = temp_final_text
                        excel_index = temp_excel_index
                        log_message(f"块 {sub.index}: [{match_type}] 成功 (相似度: {best_score:.2f}, Excel行: {matched_item['excel_row']})")

            if is_match and matched_item and matched_item['cat'] == '#反驳':
                log_message(f"  -> [反驳追认] 常规匹配命中了#反驳条目 (Excel行: {matched_item['excel_row']})，放弃当前结果并强制进入反驳模式...")
                is_match, final_text, best_score, excel_index, match_method = run_rebuke_mode(is_retroactive=True)
                if not is_match:
                    log_message(f"  -> [反驳追认] 失败，该块最终无匹配。")
            
            elif is_match and matched_item and matched_item['cat'] == '#选项':
                log_message(f"  -> [选项追认] 常规匹配命中了#选项条目 (Excel行: {matched_item['excel_row']})，放弃当前结果并强制进入选项模式...")
                is_match, final_text, best_score, excel_index, match_method = run_option_mode(is_retroactive=True)
                if not is_match:
                    log_message(f"  -> [选项追认] 失败，该块最终无匹配。")

            if not is_match and not low_score_candidate:
                cleaned_srt_full = clean_text_for_matching(original_jp_text)
                if cleaned_srt_full:
                    best_overall_match = process.extractOne(cleaned_srt_full, current_choices, scorer=fuzz.ratio)
                    if best_overall_match: best_score = best_overall_match[1] / 100.0
                    log_message(f"块 {sub.index}: [常规匹配] 失败 (最高相似度: {best_score:.2f})")
                elif not original_jp_text.strip():
                    log_message(f"块 {sub.index}: 匹配失败 (文本为空)")

            if (is_match or low_score_candidate) and use_pool_filter and matched_item:
                score_for_pool = best_score if is_match else (low_score_candidate['score'] if low_score_candidate else 0)
                if matched_item['first_match_time'] is None:
                    if score_for_pool >= pool_first_match_threshold:
                        matched_item['first_match_time'] = sub.start
                        log_message(f"    - [动态池] Excel行 {matched_item['excel_row']} 高置信度首次匹配，开始计时 (分数: {score_for_pool:.2f})。")
                    else:
                        log_message(f"    - [动态池] Excel行 {matched_item['excel_row']} 低置信度首次匹配，不启动计时 (分数: {score_for_pool:.2f} < {pool_first_match_threshold:.2f})。")
        
        elif not master_pool and not is_match:
            log_message(f"块 {sub.index}: [常规匹配] 失败 (主匹配池为空)")

        match_results.append({'sub': sub, 'original_text': original_jp_text, 'translated_text': final_text, 'is_match': is_match, 'score': best_score, 'excel_index': excel_index, 'match_method': match_method, 'low_score_candidate': low_score_candidate})
    
    df_list = df.to_dict('records')
    if use_context_rescue:
        _contextual_rescue_pass(match_results, df_list, rescue_candidate_threshold, long_text_threshold, use_context_marker, context_marker, short_sentence_length, aggressive_short_sentence_rescue, log_message)
    else:
        log_message("\n上下文救援 (插帧) 已关闭。")

    if use_legacy_rescue:
        _legacy_rescue_pass(match_results, review_threshold, upgrade_bonus_threshold, clean_text_for_matching, use_legacy_marker, legacy_marker, log_message)
    else:
        log_message("\n智能救援 (原版) 已关闭。")

    if use_single_anchor_rescue:
        _single_anchor_contextual_check_pass(match_results, df_list, single_anchor_threshold, single_anchor_neighborhood, use_context_marker, context_marker, single_anchor_aggressive_mode, single_anchor_time_threshold, log_message)
    else:
        log_message("\n单锚点上下文检查救援已关闭。")
    
    log_message("\n开始最终回填阶段...")
    回填_count = 0
    for result in match_results:
        if not result['is_match'] and result['low_score_candidate']:
            log_message(f"  -> [回填] 块 {result['sub'].index}: 低分匹配项未被任何救援覆盖，回填原结果 (分数: {result['low_score_candidate']['score']:.2f})。")
            result.update(result['low_score_candidate'])
            result['is_match'] = True
            回填_count += 1
    log_message(f"最终回填完成，共回填 {回填_count} 条字幕。")

    if use_pool_filter and should_log_details:
        log_message("\n--- [动态池最终状态报告] ---")
        remaining_count = len(master_pool)
        log_message(f"处理结束。匹配池从 {total_pool_size} 条开始，最终剩余 {remaining_count} 条。")
        if remaining_count > 0:
            log_message("以下是最终保留在匹配池中的条目 (按Excel行号排序):")
            sorted_remaining = sorted(master_pool, key=lambda x: x['excel_row'])
            for item in sorted_remaining:
                timer_status = "未计时" if item['first_match_time'] is None else f"计时中(since {str(item['first_match_time'])[:-4]})"
                log_message(f"  - Excel行 {item['excel_row']}: '{item['jp_clean'][:40]}...' ({timer_status})")
        else:
            log_message("所有条目均已被移除。")
        log_message("--- [报告结束] ---")

    for result in match_results:
        result['sub'].text = result['translated_text']
    subs.save(srt_out_path, encoding='utf-8')
    
    final_message = f"处理完成！结果已保存到 '{os.path.basename(srt_out_path)}'。"
    logs.append(f"\n{final_message}")
    return final_message, logs



def _handle_advanced_rebuke_mode(
    original_text, rebuke_pool, anchor_threshold, neighborhood_size, 
    rescue_threshold, trigger_keywords, clean_text_func, rescue_marker, log_message
):
    lines = [line.strip() for line in original_text.split('\n') if line.strip()]
    if not lines or not rebuke_pool: return False, "", 0.0

    rebuke_choices_clean = [item['jp_clean'] for item in rebuke_pool]
    used_pool_indices = set()
    
    line_statuses = []
    for i, line_text in enumerate(lines):
        is_keyword = any(k in line_text for k in trigger_keywords)
        line_statuses.append({
            "original_text": line_text, "clean_text": clean_text_func(line_text, for_comparison=False),
            "is_match": False, "is_anchor": False, "is_noise": is_keyword, "is_rescued": False,
            "score": 0.0, "translation": "", "pool_index": -1
        })

    log_message("    [高级救援-阶段1] 寻找锚点与降噪 (已启用防重复机制)...")
    for status in line_statuses:
        if status["is_noise"] or not status["clean_text"]:
            log_message(f"      - '{status['original_text']}' 是干扰项或空行，跳过。")
            continue
        
        available_choices = [(idx, choice) for idx, choice in enumerate(rebuke_choices_clean) if idx not in used_pool_indices]
        if not available_choices: continue
        
        choices_map = {i: original_idx for i, (original_idx, _) in enumerate(available_choices)}
        match = process.extractOne(status["clean_text"], [c[1] for c in available_choices], scorer=fuzz.ratio, score_cutoff=anchor_threshold * 100)
        
        if match:
            _, score, match_idx_in_available = match
            original_pool_idx = choices_map[match_idx_in_available]
            
            status.update({"is_match": True, "is_anchor": True, "score": score, "pool_index": original_pool_idx})
            matched_item = rebuke_pool[original_pool_idx]
            status["translation"] = matched_item['ch'].replace('<br>', '\\N').replace('<br><br>', '\\N\\N')
            used_pool_indices.add(original_pool_idx)
            log_message(f"      - 找到锚点: '{status['original_text']}' -> '{matched_item['jp_clean']}' (分数: {score:.2f}, Pool Idx: {original_pool_idx})")

    if not used_pool_indices:
        log_message("    [高级救援-阶段1] 未找到任何锚点，救援终止。")
        return False, "", 0.0

    log_message(f"    [高级救援-阶段2] 开始级联式邻域搜索 (救援阈值: {rescue_threshold*100:.2f})...")
    rescued_in_pass, pass_count = True, 0
    while rescued_in_pass and pass_count < len(lines):
        rescued_in_pass, pass_count = False, pass_count + 1
        log_message(f"      --- 第 {pass_count} 轮救援 ---")
        for i, status in enumerate(line_statuses):
            if status["is_noise"] or status["is_match"]: continue
            
            prev_anchor_dist, next_anchor_dist = float('inf'), float('inf')
            prev_anchor_idx, next_anchor_idx = -1, -1
            for j in range(i - 1, -1, -1):
                if line_statuses[j]["is_match"]: prev_anchor_dist, prev_anchor_idx = i - j, j; break
            for j in range(i + 1, len(line_statuses)):
                if line_statuses[j]["is_match"]: next_anchor_dist, next_anchor_idx = j - i, j; break
            
            if prev_anchor_idx == -1 and next_anchor_idx == -1: continue
            
            if prev_anchor_dist <= next_anchor_dist:
                anchor_status, direction = line_statuses[prev_anchor_idx], "down"
            else:
                anchor_status, direction = line_statuses[next_anchor_idx], "up"
            log_message(f"        - 尝试拯救 '{status['original_text']}' (基于锚点 '{anchor_status['original_text']}')")

            anchor_pool_index = anchor_status["pool_index"]
            neighborhood_pool_indices = []
            if direction == "up":
                start, end, step = anchor_pool_index - 1, -1, -1
            else:
                start, end, step = anchor_pool_index + 1, len(rebuke_pool), 1
            
            for idx in range(start, end, step):
                if len(neighborhood_pool_indices) >= neighborhood_size: break
                if idx not in used_pool_indices: neighborhood_pool_indices.append(idx)

            if not neighborhood_pool_indices:
                log_message(f"          - 邻域为空或已全部使用，无法救援。")
                continue

            neighborhood_choices_map = {i: original_idx for i, original_idx in enumerate(neighborhood_pool_indices)}
            neighborhood_choices_list = [rebuke_pool[idx]['jp_clean'] for idx in neighborhood_pool_indices]
            
            rescue_match = process.extractOne(status["clean_text"], neighborhood_choices_list, scorer=fuzz.WRatio, score_cutoff=rescue_threshold * 100)
            
            if rescue_match:
                _, score, temp_idx = rescue_match
                rescued_pool_idx = neighborhood_choices_map[temp_idx]
                status.update({"is_match": True, "is_rescued": True, "score": score, "pool_index": rescued_pool_idx})
                rescued_item = rebuke_pool[rescued_pool_idx]
                status["translation"] = rescued_item['ch'].replace('<br>', '\\N').replace('<br><br>', '\\N\\N')
                used_pool_indices.add(rescued_pool_idx)
                rescued_in_pass = True
                log_message(f"          - 救援成功! -> '{rescued_item['jp_clean']}' (分数: {score:.2f}, Pool Idx: {rescued_pool_idx})")
            else:
                log_message(f"          - 救援失败，无候选达到阈值。")

        if not rescued_in_pass: log_message("      --- 本轮无新救援，循环结束 ---")

    log_message("    [高级救援-阶段3] 最终审查与构建结果...")
    final_translations = []
    for status in sorted(line_statuses, key=lambda x: x['pool_index'] if x['is_match'] else float('inf')):
        if not status['is_match']: continue
        if status["is_match"] and status["original_text"] in trigger_keywords:
            log_message(f"      - 最终审查: 移除被误救的干扰项 '{status['original_text']}'。")
            continue
        
        final_translations.append(rescue_marker + status["translation"] if status["is_rescued"] else status["translation"])
    
    if not final_translations: return False, "", 0.0
    return True, "\\N\\N".join(final_translations) + "#反驳", 1.0

def _subriptime_to_ms(srt_time):
    if srt_time.ordinal < 0:
        return -_subriptime_to_ms(pysrt.SubRipTime.from_ordinal(-srt_time.ordinal))
    return (srt_time.hours * 3600 + srt_time.minutes * 60 + srt_time.seconds) * 1000 + srt_time.milliseconds

def _contextual_rescue_pass(match_results, df_list, rescue_candidate_threshold, long_text_threshold, use_marker, marker, short_sentence_length, aggressive_short_sentence_rescue, log_message):
    log_message(f"\n上下文救援 (插帧) 已开启 (候选阈值: <{rescue_candidate_threshold:.2f})，开始分析...")
    anchor_indices = [i for i, r in enumerate(match_results) if r['is_match'] and r['score'] >= 0.8]
    rescued_count = 0
    for i in range(len(anchor_indices) - 1):
        start_anchor_idx, end_anchor_idx = anchor_indices[i], anchor_indices[i+1]
        start_anchor, end_anchor = match_results[start_anchor_idx], match_results[end_anchor_idx]
        if start_anchor['excel_index'] == -1 or end_anchor['excel_index'] == -1:
            log_message(f"  - 锚点 {start_anchor['sub'].index}-{end_anchor['sub'].index}: 因包含高级救援结果，无法进行插帧，跳过。")
            continue
        
        # 【核心修改】将低分匹配项也视为可救援对象
        candidates_indices = [
            j for j in range(start_anchor_idx + 1, end_anchor_idx) 
            if (not match_results[j]['is_match'] or match_results[j]['low_score_candidate']) 
            and match_results[j].get('match_method') != 'long_text_filtered'
        ]

        if not candidates_indices:
            continue
        
        log_message(f"  - 锚点 {start_anchor['sub'].index}-{end_anchor['sub'].index}: 检测到 {len(candidates_indices)} 个待救援对象。")
        
        # 检查低分匹配项是否满足救援对象阈值
        valid_candidates_indices = []
        for j in candidates_indices:
            cand = match_results[j]
            # 如果是低分匹配项，它的分数必须低于“救援对象阈值”才有资格被覆盖
            if cand['low_score_candidate']:
                if cand['low_score_candidate']['score'] < rescue_candidate_threshold:
                    valid_candidates_indices.append(j)
                    log_message(f"    - 低分匹配块 {cand['sub'].index} (分数: {cand['low_score_candidate']['score']:.2f}) 符合被救援条件。")
                else:
                    log_message(f"    - 低分匹配块 {cand['sub'].index} (分数: {cand['low_score_candidate']['score']:.2f}) 分数高于救援阈值，跳过。")
            else: # 如果是未匹配项，直接加入
                valid_candidates_indices.append(j)
        
        candidates_indices = valid_candidates_indices
        if not candidates_indices:
            log_message(f"    -> 区间内无符合条件的救援对象，跳过。")
            continue

        if any(not r['original_text'].strip() for r in [match_results[j] for j in candidates_indices]):
            log_message(f"    -> 检测到空白行，放弃救援。")
            continue
        excel_dist = end_anchor['excel_index'] - start_anchor['excel_index']
        if excel_dist > 2:
            log_message(f"    -> Excel索引跨度过大 ({excel_dist})，放弃救援。")
            continue
        if excel_dist == 2 and len(candidates_indices) == 1:
            cand_idx = candidates_indices[0]
            candidate = match_results[cand_idx]
            target_excel_index = start_anchor['excel_index'] + 1
            is_short_sentence = len(candidate['original_text'].replace('\n', '')) <= short_sentence_length
            if aggressive_short_sentence_rescue and is_short_sentence:
                log_message(f"    -> [激进短句救援] 块 {candidate['sub'].index}: 识别为短句并强制桥接，填充Excel行 {target_excel_index+2}。")
                rescued_count += 1
                _apply_rescue(candidate, df_list, target_excel_index, use_marker, marker, 'contextual')
                continue 
            if len(candidate['original_text'].replace('\n', '')) <= long_text_threshold:
                log_message(f"    -> [桥接救援] 块 {candidate['sub'].index}: 成功桥接，填充Excel行 {target_excel_index+2}。")
                rescued_count += 1
                _apply_rescue(candidate, df_list, target_excel_index, use_marker, marker, 'contextual')
            else:
                log_message(f"    -> [桥接救援] 块 {candidate['sub'].index}: 因文本过长被跳过。")
            continue
        if excel_dist == 0 and len(candidates_indices) == 1:
            cand_idx = candidates_indices[0]
            candidate = match_results[cand_idx]
            log_message(f"    -> [填充救援] 块 {candidate['sub'].index}: 检测到重复帧，填充为锚点内容。")
            rescued_count += 1
            _apply_rescue(candidate, df_list, start_anchor['excel_index'], use_marker, marker, 'contextual')
            continue
        if excel_dist == 1 and len(candidates_indices) == 1:
            cand_idx = candidates_indices[0]
            candidate = match_results[cand_idx]
            gap_to_previous = candidate['sub'].start - start_anchor['sub'].end
            gap_to_next = end_anchor['sub'].start - candidate['sub'].end
            log_message(f"    - [时间邻近度分析] 块 {candidate['sub'].index}:")
            log_message(f"      - 与前锚点 {start_anchor['sub'].index} 的间隔: {_subriptime_to_ms(gap_to_previous):.0f}ms")
            log_message(f"      - 与后锚点 {end_anchor['sub'].index} 的间隔: {_subriptime_to_ms(gap_to_next):.0f}ms")
            target_excel_index = start_anchor['excel_index'] if gap_to_previous <= gap_to_next else end_anchor['excel_index']
            log_message(f"    -> [时间邻近救援] 判定: 离{'前' if gap_to_previous <= gap_to_next else '后'}锚点更近，填充为{'前' if gap_to_previous <= gap_to_next else '后'}锚点内容。")
            rescued_count += 1
            _apply_rescue(candidate, df_list, target_excel_index, use_marker, marker, 'contextual')
    log_message(f"上下文救援分析完成，共救援 {rescued_count} 条字幕。")

def _apply_rescue(target_result, df_list, source_excel_index, use_marker, marker, method_name):
    source_excel_row = df_list[source_excel_index]
    ch, cat = source_excel_row['中文'], source_excel_row['分类']
    marker_str = marker if use_marker else ""
    target_result['translated_text'] = f"{marker_str}{str(ch).replace('<br>', '\\N').replace('<br><br>', '\\N\\N')}{str(cat)}"
    target_result['is_match'] = True
    target_result['score'] = 1.0 
    target_result['excel_index'] = source_excel_index
    target_result['match_method'] = method_name
    target_result['low_score_candidate'] = None # 清除低分候选标记，因为它已经被成功救援


def _legacy_rescue_pass(match_results, review_threshold, upgrade_bonus_threshold, clean_text_func, use_marker, marker, log_message):
    log_message(f"\n智能救援 (原版) 已开启 (审查阈值: <{review_threshold:.2f}, 升级增益: >{upgrade_bonus_threshold:.2f})，开始分析...")
    if len(match_results) <= 1:
        log_message("字幕数量不足，跳过检查。")
        return
    rescue_plan = list(range(len(match_results)))
    for i in range(len(match_results) - 2, -1, -1):
        current_result = match_results[i]
        next_savior_result = match_results[rescue_plan[i+1]]
        if not next_savior_result['is_match']: continue
        current_original_clean = clean_text_func(current_result['original_text'], for_comparison=True)
        next_original_clean = clean_text_func(next_savior_result['original_text'], for_comparison=True)
        if not (current_original_clean and next_original_clean): continue
        containment_score = fuzz.partial_ratio(current_original_clean, next_original_clean) / 100.0
        if containment_score < 0.55: continue
        
        # 检查当前结果是否是“待回填的低分匹配”
        is_low_score_pending = bool(current_result['low_score_candidate'])
        
        is_failed = not current_result['is_match'] and not is_low_score_pending and current_result.get('match_method') != 'long_text_filtered'
        
        current_score = current_result['score'] if current_result['is_match'] else (current_result['low_score_candidate']['score'] if is_low_score_pending else 0)
        
        is_low_score_success = (current_result['is_match'] or is_low_score_pending) and current_score < review_threshold
        can_be_upgraded = (current_result['is_match'] or is_low_score_pending) and (containment_score > current_score + upgrade_bonus_threshold)
        
        if is_failed or is_low_score_success or can_be_upgraded:
            if is_failed: rescue_type = "追溯救援"
            elif is_low_score_success and not can_be_upgraded: rescue_type = "审查救援"
            elif can_be_upgraded: rescue_type = "竞争升级"
            else: rescue_type = "审查并升级"
            log_message(f"  [计划干预] 块 {current_result['sub'].index} ({rescue_type}) -> 将被块 {next_savior_result['sub'].index} 覆盖。")
            log_message(f"    - 原因: 当前分数({current_score:.2f}), 片段匹配度({containment_score:.2f})")
            rescue_plan[i] = rescue_plan[i+1]
            
    rescued_count = 0
    for i in range(len(match_results)):
        if rescue_plan[i] != i:
            rescued_count += 1
            current_result, savior_result = match_results[i], match_results[rescue_plan[i]]
            log_message(f"  -> [执行干预] 将块 {savior_result['sub'].index} 的结果复制到块 {current_result['sub'].index}。")
            savior_text = savior_result['translated_text']
            marker_str = marker if use_marker else ""
            if savior_text is not None and savior_text.startswith(marker):
                savior_text = savior_text[len(marker):]
            elif savior_text is None:
                savior_text = ""
            current_result['translated_text'] = f"{marker_str}{savior_text}"
            current_result['is_match'] = True
            current_result['match_method'] = 'legacy'
            current_result['low_score_candidate'] = None # 清除低分候选标记
            
    log_message(f"智能救援 (原版) 分析完成，共干预 {rescued_count} 条字幕。")

def _single_anchor_contextual_check_pass(match_results, df_list, anchor_threshold, neighborhood_size, use_marker, marker, aggressive_mode, time_threshold_ms, log_message):
    log_message(f"\n单锚点上下文检查救援已开启 (锚点阈值: >={anchor_threshold:.2f}, 检查范围: {neighborhood_size}, 时间阈值: {time_threshold_ms}ms)，开始分析...")
    rescued_count = 0
    df_len = len(df_list)
    NATIVE_MATCH_METHODS = {'direct', 'direct_rebuke', 'long_text_exempted', 'priority_exempted'}
    
    for i, result in enumerate(match_results):
        # 如果已经匹配，或者是一个待回填的低分项，就跳过
        if result['is_match'] or result['low_score_candidate'] or result.get('match_method') == 'long_text_filtered':
            continue

        rescued = False
        # [向后救援逻辑]
        if i < len(match_results) - 1:
            anchor_result = match_results[i+1]
            is_native_anchor = anchor_result.get('match_method') in NATIVE_MATCH_METHODS
            if anchor_result['is_match'] and is_native_anchor and anchor_result['score'] >= anchor_threshold and anchor_result['excel_index'] != -1:
                
                # 【核心修改-1】计算两个时间差
                # time_gap_to_anchor: 待救援行(i) 与 后锚点(i+1) 的时间差
                time_gap_to_anchor = anchor_result['sub'].start - result['sub'].end
                
                # time_gap_to_other_side: 待救援行(i) 与 另一侧物理相邻行(i-1) 的时间差
                time_gap_to_other_side = pysrt.SubRipTime(0) # 默认为0
                if i > 0:
                    time_gap_to_other_side = result['sub'].start - match_results[i-1]['sub'].end

                # 【核心修改-2】判断两个时间差是否任意一个超标
                if _subriptime_to_ms(time_gap_to_anchor) > time_threshold_ms or _subriptime_to_ms(time_gap_to_other_side) > time_threshold_ms:
                    log_message(f"  - 块 {result['sub'].index}: [向后检查救援] 否决。与后锚点({i+1})间隔({_subriptime_to_ms(time_gap_to_anchor):.0f}ms)或与前行({i-1})间隔({_subriptime_to_ms(time_gap_to_other_side):.0f}ms)超过阈值({time_threshold_ms}ms)。")
                else:
                    # 只有两个时间差都没问题，才进入救援逻辑
                    target_excel_index = anchor_result['excel_index'] - 1
                    if 0 <= target_excel_index < df_len:
                        is_safe_to_rescue = True
                        for j in range(max(0, i - neighborhood_size), i):
                            checked_block = match_results[j]
                            if checked_block['is_match'] and checked_block['excel_index'] == target_excel_index:
                                if aggressive_mode and checked_block.get('match_method') not in NATIVE_MATCH_METHODS:
                                    log_message(f"  - 块 {result['sub'].index}: [向后检查救援-激进模式] 抢占！目标Excel行 {target_excel_index + 2} 被非原生匹配块 {checked_block['sub'].index} ({checked_block.get('match_method')}) 占用，将被覆盖。")
                                else:
                                    log_message(f"  - 块 {result['sub'].index}: [向后检查救援] 否决。目标Excel行 {target_excel_index + 2} 已被块 {checked_block['sub'].index} ({checked_block.get('match_method')}) 占用。")
                                    is_safe_to_rescue = False
                                    break
                        if is_safe_to_rescue:
                            log_message(f"  -> [向后检查救援] 块 {result['sub'].index}: 基于原生锚点 {anchor_result['sub'].index} (Excel行 {anchor_result['excel_index'] + 2})，推断并填充Excel行 {target_excel_index + 2}。")
                            _apply_rescue(result, df_list, target_excel_index, use_marker, marker, 'single_anchor')
                            rescued_count += 1
                            rescued = True

        # [向前救援逻辑]
        if not rescued and i > 0:
            anchor_result = match_results[i-1]
            is_native_anchor = anchor_result.get('match_method') in NATIVE_MATCH_METHODS
            if anchor_result['is_match'] and is_native_anchor and anchor_result['score'] >= anchor_threshold and anchor_result['excel_index'] != -1:

                # 【核心修改-3】计算两个时间差
                # time_gap_to_anchor: 待救援行(i) 与 前锚点(i-1) 的时间差
                time_gap_to_anchor = result['sub'].start - anchor_result['sub'].end

                # time_gap_to_other_side: 待救援行(i) 与 另一侧物理相邻行(i+1) 的时间差
                time_gap_to_other_side = pysrt.SubRipTime(0) # 默认为0
                if i < len(match_results) - 1:
                    time_gap_to_other_side = match_results[i+1]['sub'].start - result['sub'].end

                # 【核心修改-4】判断两个时间差是否任意一个超标
                if _subriptime_to_ms(time_gap_to_anchor) > time_threshold_ms or _subriptime_to_ms(time_gap_to_other_side) > time_threshold_ms:
                    log_message(f"  - 块 {result['sub'].index}: [向前检查救援] 否决。与前锚点({i-1})间隔({_subriptime_to_ms(time_gap_to_anchor):.0f}ms)或与后行({i+1})间隔({_subriptime_to_ms(time_gap_to_other_side):.0f}ms)超过阈值({time_threshold_ms}ms)。")
                else:
                    # 只有两个时间差都没问题，才进入救援逻辑
                    target_excel_index = anchor_result['excel_index'] + 1
                    if 0 <= target_excel_index < df_len:
                        is_safe_to_rescue = True
                        for j in range(i + 1, min(i + 1 + neighborhood_size, len(match_results))):
                            checked_block = match_results[j]
                            if checked_block['is_match'] and checked_block['excel_index'] == target_excel_index:
                                if aggressive_mode and checked_block.get('match_method') not in NATIVE_MATCH_METHODS:
                                    log_message(f"  - 块 {result['sub'].index}: [向前检查救援-激进模式] 抢占！目标Excel行 {target_excel_index + 2} 在后续被非原生匹配块 {checked_block['sub'].index} ({checked_block.get('match_method')}) 占用，将被覆盖。")
                                else:
                                    log_message(f"  - 块 {result['sub'].index}: [向前检查救援] 否决。目标Excel行 {target_excel_index + 2} 已在后续被块 {checked_block['sub'].index} ({checked_block.get('match_method')}) 占用。")
                                    is_safe_to_rescue = False
                                    break
                        if is_safe_to_rescue:
                            log_message(f"  -> [向前检查救援] 块 {result['sub'].index}: 基于原生锚点 {anchor_result['sub'].index} (Excel行 {anchor_result['excel_index'] + 2})，推断并填充Excel行 {target_excel_index + 2}。")
                            _apply_rescue(result, df_list, target_excel_index, use_marker, marker, 'single_anchor')
                            rescued_count += 1
                            rescued = True

    log_message(f"单锚点上下文检查救援分析完成，共救援 {rescued_count} 条字幕。")

# 【核心修改】修改 format_srt_file 函数签名和内部逻辑
def format_srt_file(srt_in_path, srt_out_path, replace_link, replace_color, replace_ruby, link_color_hex, color_color_hex, split_options_rebukes, merge_duplicate_groups, connect_timelines, max_connection_gap_ms):
    def hex_to_ass_color(hex_str):
        if not hex_str or len(hex_str) != 6: return "&H000000&"
        r, g, b = hex_str[0:2], hex_str[2:4], hex_str[4:6]
        return f"&H{b.upper()}{g.upper()}{r.upper()}&"

    subs = pysrt.open(srt_in_path, encoding='utf-8')
    
    link_ass_color, color_ass_color = hex_to_ass_color(link_color_hex), hex_to_ass_color(color_color_hex)
    link_pattern = std_re.compile(r'<link="Objection_(?:[0-9]{2}_?)+">(.*?)</link>')
    color_pattern = std_re.compile(r'<color=#9c8eff>(.*?)</color>')
    ruby_pattern = std_re.compile(r'<ruby=".*?">(.*?)</ruby>')
    
    pre_processed_subs = []
    for sub in subs:
        text = sub.text
        is_option = text.endswith("#选项")
        is_rebuke = text.endswith("#反驳")

        if (is_option or is_rebuke) and split_options_rebukes:
            base_tag = "#选项" if is_option else "#反驳"
            content = text[:-len(base_tag)].strip()
            lines = content.split('\\N\\N')
            num_lines = len(lines)
            
            if num_lines > 1:
                for i, line in enumerate(lines):
                    if not line.strip(): continue
                    new_sub = pysrt.SubRipItem()
                    new_sub.start, new_sub.end = sub.start, sub.end
                    suffix = chr(ord('a') + i)
                    new_tag = f"{base_tag}{num_lines}{suffix}"
                    new_sub.text = f"{line.strip()}{new_tag}"
                    pre_processed_subs.append(new_sub)
            else:
                sub.text = f"{content}{base_tag}1"
                pre_processed_subs.append(sub)
        else:
            text = text.replace('\\N\\N', '\\N')
            if replace_ruby: text = ruby_pattern.sub(lambda m: m.group(1), text)
            if replace_link: text = link_pattern.sub(lambda m: f"{{\\c{link_ass_color}}}{m.group(1)}{{\\c}}", text)
            if replace_color: text = color_pattern.sub(lambda m: f"{{\\c{color_ass_color}\\1a&H00&}}{m.group(1)}{{\\c}}", text)
            sub.text = text
            pre_processed_subs.append(sub)

    final_subs = []
    if not merge_duplicate_groups:
        final_subs = pre_processed_subs
    else:
        group_pattern = std_re.compile(r'#(选项|反驳)(\d+)([a-z])$')
        last_group_content = None
        last_group_indices_in_final = []
        
        i = 0
        while i < len(pre_processed_subs):
            current_sub = pre_processed_subs[i]
            match = group_pattern.search(current_sub.text)
            
            if match:
                base_type, num_str, _ = match.groups()
                group_size = int(num_str)
                
                if i + group_size > len(pre_processed_subs):
                    final_subs.append(current_sub)
                    i += 1
                    continue

                current_group_subs = pre_processed_subs[i : i + group_size]
                current_group_content = []
                is_valid_group = True
                
                for k, sub_in_group in enumerate(current_group_subs):
                    g_match = group_pattern.search(sub_in_group.text)
                    expected_suffix = chr(ord('a') + k)
                    if not (g_match and g_match.group(1) == base_type and g_match.group(2) == num_str and g_match.group(3) == expected_suffix):
                        is_valid_group = False
                        break
                    current_group_content.append(group_pattern.sub('', sub_in_group.text).strip())
                
                if not is_valid_group:
                    final_subs.append(current_sub)
                    i += 1
                    continue
                
                if current_group_content == last_group_content:
                    new_end_time = current_group_subs[-1].end
                    for sub_index in last_group_indices_in_final:
                        final_subs[sub_index].end = new_end_time
                    i += group_size
                else:
                    start_index_in_final = len(final_subs)
                    final_subs.extend(current_group_subs)
                    last_group_content = current_group_content
                    last_group_indices_in_final = list(range(start_index_in_final, len(final_subs)))
                    i += group_size
            else:
                final_subs.append(current_sub)
                last_group_content = None
                last_group_indices_in_final = []
                i += 1

    # 【核心修改】时间轴连接逻辑
    if connect_timelines:
        for i in range(1, len(final_subs)):
            prev_sub = final_subs[i-1]
            curr_sub = final_subs[i]
            
            is_prev_option_or_rebuke = "#选项" in prev_sub.text or "#反驳" in prev_sub.text
            is_curr_option_or_rebuke = "#选项" in curr_sub.text or "#反驳" in curr_sub.text

            if not (is_prev_option_or_rebuke or is_curr_option_or_rebuke):
                if curr_sub.text.strip() and prev_sub.text.strip() and curr_sub.start > prev_sub.end:
                    # 计算时间间隔
                    gap_ms = _subriptime_to_ms(curr_sub.start - prev_sub.end)
                    # 只有间隔小于等于阈值才连接
                    if gap_ms <= max_connection_gap_ms:
                        curr_sub.start = prev_sub.end

    subs.clear()
    subs.extend(final_subs)
    subs.clean_indexes()
    subs.save(srt_out_path, encoding='utf-8')
    
    return f"格式化处理完成！已保存到 '{os.path.basename(srt_out_path)}'。"

def read_subs_from_file(filepath, encoding='utf-8'):
    _, ext = os.path.splitext(filepath)
    if ext.lower() == '.ass':
        subs = pysrt.SubRipFile()
        dialogue_pattern = std_re.compile(
            r'Dialogue:\s*\d+,'          # Layer
            r'(\d+:\d{2}:\d{2}\.\d{2}),'  # Start
            r'(\d+:\d{2}:\d{2}\.\d{2}),'  # End
            r'([^,]*),'                  # Style
            r'([^,]*),'                  # Name
            r'([^,]*),'                  # MarginL
            r'([^,]*),'                  # MarginR
            r'([^,]*),'                  # MarginV
            r'([^,]*),'                  # Effect
            r'(.*)'                      # Text
        )
        with open(filepath, 'r', encoding=encoding) as f:
            for line in f:
                match = dialogue_pattern.match(line)
                if match:
                    start_str, end_str, style, _, _, _, _, _, text = match.groups()
                    def time_str_to_ms(ts):
                        h, m, s_ms = ts.split(':')
                        s, ms = s_ms.split('.')
                        return int(h)*3600000 + int(m)*60000 + int(s)*1000 + int(ms)*10
                    start_time = pysrt.SubRipTime.from_ordinal(time_str_to_ms(start_str))
                    end_time = pysrt.SubRipTime.from_ordinal(time_str_to_ms(end_str))
                    text = text.replace('\\N', '\n')
                    if style and style != "Default":
                        text += f"#{style}"
                    sub_item = pysrt.SubRipItem(
                        index=len(subs) + 1, start=start_time, end=end_time, text=text
                    )
                    subs.append(sub_item)
        return subs
    else:
        return pysrt.open(filepath, encoding=encoding)

