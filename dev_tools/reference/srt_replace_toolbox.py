class ScrollableFrame(ttk.Frame):
    def __init__(self, container, *args, **kwargs):
        super().__init__(container, *args, **kwargs)
        self.canvas = tk.Canvas(self, highlightthickness=0)
        scrollbar = ttk.Scrollbar(self, orient="vertical", command=self.canvas.yview)
        self.scrollable_frame = ttk.Frame(self.canvas)
        self.scrollable_frame.bind("<Configure>", lambda e: self.canvas.configure(scrollregion=self.canvas.bbox("all")))
        self.canvas.create_window((0, 0), window=self.scrollable_frame, anchor="nw")
        self.canvas.configure(yscrollcommand=scrollbar.set)
        self.canvas.pack(side="left", fill="both", expand=True); scrollbar.pack(side="right", fill="y")
        self.scrollable_frame.bind("<Enter>", self._bind_mouse); self.scrollable_frame.bind("<Leave>", self._unbind_mouse)
    def _bind_mouse(self, event=None):
        self.canvas.bind_all("<MouseWheel>", self._on_mousewheel)
        for child in self.scrollable_frame.winfo_children():
            child.bind("<Enter>", self._bind_mouse); child.bind("<Leave>", self._unbind_mouse)
    def _unbind_mouse(self, event=None): self.canvas.unbind_all("<MouseWheel>")
    def _on_mousewheel(self, event):
        if event.delta: self.canvas.yview_scroll(int(-1*(event.delta/120)), "units")
        else:
            if event.num == 5: self.canvas.yview_scroll(1, "units")
            elif event.num == 4: self.canvas.yview_scroll(-1, "units")

