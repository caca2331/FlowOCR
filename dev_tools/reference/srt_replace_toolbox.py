    def format_time(t):
        return f"{t.hours}:{t.minutes:02d}:{t.seconds:02d}.{t.milliseconds//10:02d}"

    try:
        subs = read_subs_from_file(srt_in_path)
        total_subs = len(subs)
        log_message(f"成功读取字幕文件，共 {total_subs} 条字幕。")
    except Exception as e: raise IOError(f"读取字幕文件 '{os.path.basename(srt_in_path)}' 失败: {e}")

