    def _parse_default_styles(self):
        header_lines = DEFAULT_ASS_HEADER.splitlines(); format_line, style_lines, in_styles_section = "", [], False
        for line in header_lines:
            if line.strip() == "[V4+ Styles]": in_styles_section = True; continue
            if in_styles_section:
                if line.lower().startswith("format:"): format_line = line.split(":", 1)[1].strip()
                elif line.lower().startswith("style:"): style_lines.append(line.split(":", 1)[1].strip())
                elif line.strip().startswith("["): break
        if not format_line or not style_lines: return
        keys = [key.strip() for key in format_line.split(',')]
        for line in style_lines:
            values = [val.strip() for val in line.split(',', len(keys) - 1)]
            style_dict = dict(zip(keys, values))
            if style_name := style_dict.get("Name"): self.styles_data[style_name] = style_dict
