    def _ass_color_to_hex(self, ass_color):
        if not ass_color.startswith('&H') or len(ass_color) < 8: return "FFFFFF"
        b, g, r = ass_color[4:6], ass_color[6:8], ass_color[8:10] if len(ass_color) > 8 else (ass_color[2:4], ass_color[4:6], ass_color[6:8])
        return f"{r}{g}{b}".upper()
    def _hex_to_ass_color(self, hex_color):
        if len(hex_color) != 6: return "&H00FFFFFF&"
        r, g, b = hex_color[0:2], hex_color[2:4], hex_color[4:6]
        return f"&H00{b}{g}{r}".upper()
