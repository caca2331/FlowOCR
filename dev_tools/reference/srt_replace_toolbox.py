    def process_tab4(self):
        srt_path, ass_path = self.tab4_srt_path.get(), self.tab4_ass_path.get()
        mappings_str = self.tab4_mappings_text.get("1.0", tk.END)
        remove_blanks = self.tab4_remove_blank_lines.get()
        remove_sus = self.tab4_remove_sus_marker.get()
        if not srt_path or not ass_path: messagebox.showerror("错误", "请选择源文件和保存位置！"); return
        style_mappings = {}
        try:
            for line in mappings_str.strip().split('\n'):
                if ':' in line: identifier, style_name = line.split(':', 1); style_mappings[identifier.strip()] = style_name.strip()
        except Exception as e: messagebox.showerror("错误", f"样式映射格式错误: {e}"); return
        if not style_mappings: messagebox.showwarning("警告", "未定义任何样式映射，所有字幕将使用'Default'样式。")
        self.tab4_button.config(state="disabled"); self.tab4_progress_var.set(0); self.tab4_progress_label_var.set("准备开始...")
        self.tab4_start_time = time.time()
        self.start_threaded_task(self.run_tab4_logic, srt_path, ass_path, style_mappings, "Default", remove_blanks, remove_sus, self.styles_data, self.tab4_should_log_details.get())
    def run_tab4_logic(self, srt_path, ass_path, style_mappings, default_style, remove_blank_lines, remove_sus_marker, styles_data, should_log_details):
        try:
            result, logs = convert_srt_to_styled_ass(srt_path, ass_path, style_mappings, default_style, remove_blank_lines, remove_sus_marker, styles_data, progress_callback=lambda cur, tot: self.parent.after(0, self.update_progress, cur, tot, self.tab4_start_time, self.tab4_progress_var, self.tab4_progress_label_var), should_log_details=should_log_details)
            self.parent.after(0, self.on_tab4_success, result, logs, ass_path, should_log_details)
        except Exception as e: self.parent.after(0, self.on_tab4_error, str(e))
    def on_tab4_success(self, message, logs, ass_path, should_log_details):
        if should_log_details and logs:
            log_file_path = os.path.splitext(ass_path)[0] + ".log"
            with open(log_file_path, 'w', encoding='utf-8') as f: f.write("\n".join(logs))
            log_msg = "详细日志已生成。"
        else: log_msg = "详细日志未输出。"
        elapsed_time = time.time() - self.tab4_start_time
        self.tab4_progress_label_var.set(f"任务完成！总耗时: {elapsed_time:.2f} 秒。{log_msg}")
        self.tab4_button.config(state="normal"); messagebox.showinfo("成功", message)
    def on_tab4_error(self, error_message):
        self.tab4_progress_label_var.set(f"任务失败: {error_message}"); self.tab4_button.config(state="normal"); messagebox.showerror("失败", f"处理失败: {error_message}")

